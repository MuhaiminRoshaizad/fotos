"""Writes fotos' flower as Android resources: the adaptive icon, the themed
(monochrome) icon, the animated launch-screen icon and a still one for
Android 11. One petal path and one colour list, so they cannot drift apart.
Run from the repository root."""
import io

RES = 'android/app/src/main/res/'
PETAL = 'M0,-10 C16,-30 42,-62 42,-90 A42,42 0 0 0 -42,-90 C-42,-62 -16,-30 0,-10 Z'
COLORS = ['#FF5F6D', '#FFB347', '#FFE66D', '#4FD1A5', '#5B9BFF', '#B388FF']
N = 6
OUTER = 132.0  # the petal's reach from the centre, in path units
HEAD = '<?xml version="1.0" encoding="utf-8"?>\n'


def write(name, text):
    io.open(RES + name, 'w', encoding='utf-8', newline='\n').write(text)


def still(size, radius, note, mono=False, core='#FFFFFF'):
    k = radius / OUTER
    c = size / 2
    out = [HEAD, '<!-- %s Generated by tool/gen_icon.py. -->\n' % note,
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
           '    android:width="%ddp"\n    android:height="%ddp"\n'
           '    android:viewportWidth="%d"\n    android:viewportHeight="%d">\n' % (size, size, size, size),
           '    <group android:translateX="%g" android:translateY="%g" android:scaleX="%.4f" android:scaleY="%.4f">\n' % (c, c, k, k)]
    for i in range(N):
        out.append('        <group android:rotation="%d">\n            <path android:fillColor="%s" android:fillAlpha="%s" android:pathData="%s" />\n        </group>\n'
                   % (i * 360 // N, '#FFFFFF' if mono else COLORS[i], '1' if mono else '0.92', PETAL))
    if not mono:
        out.append('        <path android:fillColor="%s" android:pathData="M-9,0 a9,9 0 1 0 18,0 a9,9 0 1 0 -18,0 Z" />\n' % core)
    out.append('    </group>\n</vector>\n')
    return ''.join(out)


def animated():
    size, radius = 288, 84.0
    k = radius / OUTER
    o = [HEAD,
         '<!-- The launch screen\'s icon on Android 12 and later: the six petals are\n'
         '     pulled in to the centre and lock into the flower. Each starts far out\n'
         '     and turned, accelerates inward, passes its place slightly and settles.\n'
         '     Under one second in all, which is what Android allows here.\n'
         '     Generated by tool/gen_icon.py. -->\n',
         '<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
         '    xmlns:aapt="http://schemas.android.com/aapt">\n'
         '    <aapt:attr name="android:drawable">\n'
         '        <vector android:width="288dp" android:height="288dp"\n'
         '            android:viewportWidth="288" android:viewportHeight="288">\n'
         '            <group android:translateX="144" android:translateY="144" android:scaleX="%.4f" android:scaleY="%.4f">\n' % (k, k)]
    for i in range(N):
        a = i * 360 // N
        o.append('                <group android:name="r%d" android:rotation="%d">\n'
                 '                    <group android:name="t%d" android:translateY="-330" android:scaleX="0.7" android:scaleY="0.7">\n'
                 '                        <path android:name="f%d" android:fillColor="%s" android:fillAlpha="0" android:pathData="%s" />\n'
                 '                    </group>\n                </group>\n' % (i, a + 70, i, i, COLORS[i], PETAL))
    o.append('                <group android:name="core" android:scaleX="0" android:scaleY="0">\n'
             '                    <path android:fillColor="@color/splash_core" android:pathData="M-9,0 a9,9 0 1 0 18,0 a9,9 0 1 0 -18,0 Z" />\n'
             '                </group>\n            </group>\n        </vector>\n    </aapt:attr>\n')

    def anim(prop, frm, to, dur, off, interp, vtype='floatType'):
        return ('                <objectAnimator android:propertyName="%s" android:valueFrom="%s" android:valueTo="%s"\n'
                '                    android:valueType="%s" android:duration="%d" android:startOffset="%d"\n'
                '                    android:interpolator="@android:interpolator/%s" />\n' % (prop, frm, to, vtype, dur, off, interp))

    def target(name, body):
        return ('    <target android:name="%s">\n        <aapt:attr name="android:animation">\n            <set android:ordering="together">\n%s'
                '            </set>\n        </aapt:attr>\n    </target>\n' % (name, body))

    for i in range(N):
        a = i * 360 // N
        d = i * 55
        o.append(target('r%d' % i, anim('rotation', a + 70, a, 560, d, 'fast_out_slow_in')))
        o.append(target('t%d' % i,
                        anim('translateY', -330, 12, 440, d, 'accelerate_cubic') +
                        anim('translateY', 12, 0, 200, d + 440, 'decelerate_cubic') +
                        anim('scaleX', 0.7, 1, 620, d, 'fast_out_slow_in') +
                        anim('scaleY', 0.7, 1, 620, d, 'fast_out_slow_in')))
        o.append(target('f%d' % i, anim('fillAlpha', 0, 0.92, 260, d, 'linear')))
    o.append(target('core', anim('scaleX', 0, 1, 220, 700, 'decelerate_cubic') + anim('scaleY', 0, 1, 220, 700, 'decelerate_cubic')))
    o.append('</animated-vector>\n')
    return ''.join(o)


write('drawable/ic_launcher_foreground.xml',
      still(108, 30, 'fotos\' launcher icon: six petals in the spectrum colours, kept inside the adaptive icon\'s safe circle.'))
write('drawable/ic_launcher_monochrome.xml',
      still(108, 30, 'The flower in one colour, for Android\'s themed icons.', mono=True))
write('drawable/splash_flower.xml', animated())
write('drawable/splash_flower_still.xml',
      still(288, 84, 'The assembled flower, for the launch screen on Android 11, which cannot animate one.', core='@color/splash_core'))
print('ok')
